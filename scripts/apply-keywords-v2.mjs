// Keyword strategy v2 -> site data.
//   Source: ../SEO Analysis/mapping-v2.json (engine2.js) and ../SEO Analysis/blog-seo.json (blogs.js + blogs2.js).
//   Rules: Semrush bank only, KD <= 28. Primary = Transactional. Secondary = 15 (Commercial first). Tags = 20 Commercial.
//          Blogs / FAQ use Navigational + Informational for primary and secondary; blog tags are Commercial.
//   Writes: lib/data/seo-keywords.ts, lib/data/blog-seo.ts.   Then run: node scripts/apply-seo-content.mjs
import fs from 'node:fs';
import path from 'node:path';

const ROOT = process.cwd();
const A = path.resolve(ROOT, '..', 'SEO Analysis');
const MAP = JSON.parse(fs.readFileSync(path.join(A, 'mapping-v2.json'), 'utf8'));
const BLOG = JSON.parse(fs.readFileSync(path.join(A, 'blog-seo.json'), 'utf8'));

// ---------- seo-keywords.ts (per sub-category set + site tags) ----------
const oldTs = fs.readFileSync(path.join(ROOT, 'lib/data/seo-keywords.ts'), 'utf8');
const header = oldTs.slice(0, oldTs.indexOf('export const SEO_KEYWORDS'));
const oldJson = oldTs.slice(oldTs.indexOf('= {', oldTs.indexOf('SEO_KEYWORDS')) + 2, oldTs.indexOf(';\n\nexport const SITE_TAGS'));
const OLD = JSON.parse(oldJson);

const set = {};
for (const e of MAP.subcategories) {
  const o = OLD[e.slug] || {};
  const p = e.primary || e.fallbackPrimary;
  const secondary = e.secondary.map((k) => k.kw);
  const tags = e.tags.map((k) => k.kw);
  set[e.slug] = {
    primary: p ? p.kw : o.primary || e.name.toLowerCase(),
    primaryVolume: p ? p.vol : o.primaryVolume ?? 0,
    primaryKd: p ? p.kd : o.primaryKd ?? null,
    secondary,
    tags,
    faqSeeds: e.informational.map((k) => ({ keyword: k.kw, volume: k.vol, kd: k.kd, intent: k.intent })),
    informational: e.informational.map((k) => ({ keyword: k.kw, volume: k.vol, kd: k.kd, intent: k.intent })),
    transactional: e.secondary.concat(e.tags).filter((k) => k.intent === 'Transactional').map((k) => k.kw),
  };
}
// home / site-wide tags: highest-volume Transactional + Commercial keywords used anywhere in the map (KD <= 28 already)
const pool = new Map();
const addK = (k) => { if (k && (k.intent === 'Transactional' || k.intent === 'Commercial')) pool.set(k.kw, Math.max(pool.get(k.kw) || 0, k.vol)); };
for (const t of ['categories', 'subcategories', 'pages']) for (const e of MAP[t]) { addK(e.primary); (e.secondary || []).forEach(addK); (e.tags || []).forEach(addK); }
const SITE_TAGS = [...pool.entries()].sort((a, b) => b[1] - a[1]).map(([k]) => k).slice(0, 150);

fs.writeFileSync(
  path.join(ROOT, 'lib/data/seo-keywords.ts'),
  `${header}export const SEO_KEYWORDS: Record<string, SeoKeywordSet> = ${JSON.stringify(set, null, 1)};\n\nexport const SITE_TAGS: string[] = ${JSON.stringify(SITE_TAGS)};\n`,
);

// ---------- blog-seo.ts ----------
const blogSeo = {};
for (const [slug, v] of Object.entries(BLOG)) blogSeo[slug] = { primaryKeyword: v.primary, secondaryKeywords: v.secondary, tags: v.tags };
fs.writeFileSync(
  path.join(ROOT, 'lib/data/blog-seo.ts'),
  `// GENERATED by scripts/apply-keywords-v2.mjs from the Whisky Keywords Bank (Semrush) - do not edit by hand.\n// Primary + 15 secondary = Navigational / Informational keywords (KD <= 28). tags = 20 Commercial keywords.\nexport const BLOG_SEO: Record<string, { primaryKeyword: string; secondaryKeywords: string[]; tags: string[] }> = ${JSON.stringify(blogSeo, null, 1)};\n`,
);
console.log(`seo-keywords.ts: ${Object.keys(set).length} sub-categories, ${SITE_TAGS.length} site tags; blog-seo.ts: ${Object.keys(blogSeo).length} posts`);

// ---------- home-seo.ts (homepage primary + 15 secondary + tags: Transactional / Commercial, KD <= 28) ----------
const home = JSON.parse(fs.readFileSync(path.join(A, 'home-seo.json'), 'utf8'));
fs.writeFileSync(
  path.join(ROOT, 'lib/data/home-seo.ts'),
  `// GENERATED by scripts/apply-keywords-v2.mjs from ../SEO Analysis/home.js (Semrush bank, KD <= 28) - do not edit by hand.\n// primary = highest-volume Transactional keyword; primaries = next Transactional; secondary = 15; tags = the visible tags line (Commercial + Transactional, highest volume).\nexport const HOME_SEO = ${JSON.stringify({ primary: home.primary, primaries: home.primaries.map((k) => ({ kw: k.kw, vol: k.vol })), secondary: home.secondary.map((k) => ({ kw: k.kw, vol: k.vol })), tags: home.tags.map((k) => ({ kw: k.kw, vol: k.vol })), headline: home.headline }, null, 1)};\n`,
);
console.log('home-seo.ts written');

// ---------- page-seo.ts (Shop / About / Shipping / Contact / FAQ / Blog index) ----------
const PAGES = JSON.parse(fs.readFileSync(path.join(A, 'page-seo.json'), 'utf8'));
fs.writeFileSync(
  path.join(ROOT, 'lib/data/page-seo.ts'),
  `// GENERATED by scripts/apply-keywords-v2.mjs from the Whisky Keywords Bank (Semrush, KD <= 28) - do not edit by hand.\n// Shop / About / Shipping / Contact: Transactional primary + Commercial secondary. FAQ / Blog index: Navigational + Informational.\nexport interface PageSeo { primary: string; secondary: string[]; tags: string[] }\nexport const PAGE_SEO: Record<string, PageSeo> = ${JSON.stringify(Object.fromEntries(Object.entries(PAGES).map(([k, v]) => [k, { primary: v.primary.kw, secondary: v.secondary.map((s) => s.kw), tags: v.tags.map((s) => s.kw) }])), null, 1)};\n`,
);
console.log('page-seo.ts written');

// ---------- category-seo.ts (4 shop categories) ----------
const CATS = Object.fromEntries(MAP.categories.map((c) => [c.slug, { primary: (c.primary || c.fallbackPrimary).kw, secondary: c.secondary.map((k) => k.kw), tags: c.tags.map((k) => k.kw) }]));
fs.writeFileSync(
  path.join(ROOT, 'lib/data/category-seo.ts'),
  `// GENERATED by scripts/apply-keywords-v2.mjs from the Whisky Keywords Bank (Semrush, KD <= 28) - do not edit by hand.\nexport const CATEGORY_SEO: Record<string, { primary: string; secondary: string[]; tags: string[] }> = ${JSON.stringify(CATS, null, 1)};\n`,
);
console.log('category-seo.ts written');
